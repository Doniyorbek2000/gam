// Generates src/seed.ts (first-run content for the server's config storage) from the client's economy tables,
// so crate odds, pools and prices have one source: Assets/_Project/Resources/Economy/{crates,catalog}.json.
// The admin panel (M4) overwrites config/<name> at runtime; this is only the seed.
const fs = require("node:fs");
const path = require("node:path");

const economy = path.join(__dirname, "..", "..", "..", "..", "Assets", "_Project", "Resources", "Economy");
const read = (name) => JSON.parse(fs.readFileSync(path.join(economy, name), "utf8"));
const liveops = require("./liveops-seed");

const seed = {
    catalog: read("catalog.json"),
    crates: read("crates.json"),
    // docs/ECONOMY.md §4.3 direct prices per rarity (0 = not sold for that currency).
    shop: { coin: [1500, 6000, 0, 0, 0], gem: [0, 150, 450, 1400, 0] },
    // docs/GDD.md §6.5: 7-day cycle; a missed day keeps the progress.
    login: {
        days: [
            { coins: 200 }, { coins: 300 }, { key_classic: 1 }, { coins: 500 },
            { gems: 10 }, { coins: 800 }, { key_premium: 1 },
        ],
    },
    start: { coins: 5000, gems: 500 },
    ...liveops,
};

const out = "// GENERATED by scripts/gen-seed.js from Assets/_Project/Resources/Economy — do not edit.\n" +
    "var SEED_CONFIG: { [name: string]: any } = " + JSON.stringify(seed, null, 4) + ";\n";
fs.writeFileSync(path.join(__dirname, "..", "src", "seed.ts"), out);
console.log("seed.ts: " + seed.catalog.items.length + " items, " + seed.crates.crates.length + " crates");
